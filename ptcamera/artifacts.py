def write_metrics(s, path):
    def sci(v):
        mantissa, exponent = f"{v:.2e}".split("e")
        return rf"{mantissa}\times 10^{{{int(exponent)}}}"

    values = {
        "HeightAreaMin": f"{s['height']['area_min_m2']:.2f}",
        "HeightAreaMax": f"{s['height']['area_max_m2']:.2f}",
        "HeightAreaError": sci(s["height"]["max_relative_area_error"]),
        "PanAreaError": sci(s["pan"]["max_relative_area_change"]),
        "TiltAreaFirst": f"{s['tilt']['area_first_m2']:.2f}",
        "TiltAreaLast": f"{s['tilt']['area_last_m2']:.2f}",
        "EntryTime": f"{s['target_motion']['entry_theory_s']:.4f}",
        "ExitTime": f"{s['target_motion']['exit_theory_s']:.4f}",
        "FirstSampleTime": f"{s['target_motion']['first_visible_sample_s']:.2f}",
        "LastSampleTime": f"{s['target_motion']['last_visible_sample_s']:.2f}",
        "ImageSpeed": f"{s['target_motion']['image_speed_mm_s']:.4f}",
        "VisibleSamples": str(s["target_motion"]["visible_samples"]),
        "MotionSamples": str(s["target_motion"]["samples"]),
        "CriticalHeight": f"{s['occlusion']['critical_height_m']:.1f}",
        "NoiseError": f"{s['noise']['max_abs_rmse_difference_mm']:.6f}",
        "NoisePercentError": f"{s['noise']['max_relative_rmse_difference']*100:.3f}",
        "NoiseMaxRMSE": f"{s['noise']['rmse_at_max_sigma_mm']:.6f}",
        "JacobianFirst": sci(s["sensitivity"]["max_error_at_first_step"]),
        "JacobianLast": sci(s["sensitivity"]["max_error_at_last_step"]),
    }
    Path(path).write_text(
        "% Generated by run.py from results/summary.json; do not edit.\n"
        + "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in values.items())
        + "\n"
    )


