def package_project(root):
    """Build full project and self-contained Overleaf ZIP, without Git/caches."""
    root = Path(root)
    required = [
        "report/main.pdf",
        "report/main.tex",
        "report/metrics.tex",
        "results/summary.json",
        "results/media/pt_motion.mp4",
        "results/media/pt_motion.gif",
    ]
    for name in required:
        if not (root / name).is_file():
            raise FileNotFoundError(f"Missing {name}; run with --media --report first")
    # Check source-referenced figures exist before packaging.
    source = (root / "report/main.tex").read_text()
    for name in re.findall(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", source):
        if not (root / "results/figures" / name).exists():
            raise FileNotFoundError(name)
    dest = root / "downloads"
    dest.mkdir(exist_ok=True)
    excluded = {".git", "__pycache__", ".venv", "downloads", ".mplconfig"}
    paths = [
        p
        for p in root.rglob("*")
        if p.is_file()
        and not any(part in excluded for part in p.relative_to(root).parts)
        and p.suffix not in {".aux", ".log", ".out", ".pyc", ".toc", ".gz"}
    ]
    with zipfile.ZipFile(
        dest / "PT-camera-final-project.zip", "w", zipfile.ZIP_DEFLATED
    ) as z:
        for p in sorted(paths):
            z.write(p, "MidtermProject/" + str(p.relative_to(root)))
    with zipfile.ZipFile(
        dest / "PT-camera-final-report.zip", "w", zipfile.ZIP_DEFLATED
    ) as z:
        for p in (root / "report").iterdir():
            if p.suffix in {".tex", ".pdf", ".md"}:
                # Same source; local figure path makes the report ZIP self-contained.
                if p.name == "main.tex":
                    z.writestr(
                        "main.tex",
                        p.read_text().replace("../results/figures/", "figures/"),
                    )
                else:
                    z.write(p, p.name)
        for p in (root / "results/figures").glob("*.pdf"):
            z.write(p, "figures/" + p.name)
    for p in dest.glob("PT-camera-final-*.zip"):
        with zipfile.ZipFile(p) as z:
            if z.testzip() is not None:
                raise RuntimeError(f"Archive check failed: {p}")
        print(f"Package: {p.name} ({p.stat().st_size:,} bytes)", flush=True)
